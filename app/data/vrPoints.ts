export interface VRPoint {
  id: string;
  venueId: 'lotte-concert-hall' | 'sac-concert-hall';
  floor: number;
  /** 'B', 'R', 'BOX3' 등. 모르면 null (지금은 전부 채워져 있다) */
  block: string | null;
  /** 공식 자료가 열을 명시하지 않으면 null */
  row: number | null;
  /** 좌석 번호. 롯데는 지점 단위라 항상 null */
  number: number | null;
  /** '1층 B구역 중앙' 같은 사람이 읽는 설명 */
  label: string;
  /** `app/assets/vr/` 기준 상대 경로 */
  asset: string;
  /** 공식 배치도 픽셀 좌표 (출처 추적·디버그용) */
  mapX: number;
  mapY: number;
  /** 배치도상 무대 중심에서의 거리. 같은 구역 안의 깊이 순서에만 쓴다. 예당은 null */
  stageDist: number | null;
  /** 출처 페이지 (저작권 추적용) */
  sourceUrl: string;
  /** 원본 자산 URL (저작권 추적용) */
  assetUrl: string;
  confidence: 'confirmed' | 'inferred';
}

/** 화면이 <img src> 로 바로 쓸 수 있는 형태 */
export interface ResolvedVRPoint extends VRPoint {
  /** 번들러가 해결한 실제 URL. 자산 파일이 없으면 null */
  image: string | null;
}

/* ------------------------------------------------------------------ *
 * 자산 경로를 아는 **단 하나의 지점**
 * ------------------------------------------------------------------ *
 * 절차적 생성으로 갈아끼울 때 여기만 바꾸면 된다.
 * import.meta.glob 은 vite 전용이라 Node(테스트)에서는 빈 표가 되고,
 * 그때 image 는 null 이 된다 — 매칭 로직 자체는 그대로 동작한다.
 */
const VR_ASSETS: Record<string, string> = (() => {
  // import.meta.glob 은 vite 의 **컴파일 타임 매크로**다. 런타임 import.meta 에는
  // glob 속성이 없으므로 `typeof import.meta.glob === 'function'` 같은 사전 검사를
  // 두면 vite 빌드에서도 항상 거짓이 되어 자산 표가 통째로 비어버린다.
  // 그래서 검사 없이 바로 호출하고, vite 가 아닌 환경(Node 테스트)에서만
  // 예외가 나므로 그걸 잡아 빈 표로 떨어뜨린다 — 그때 image 는 null 이고
  // 매칭 로직 자체는 그대로 동작한다.
  try {
    // @ts-ignore vite 전용 API (tsconfig types 에 vite/client 가 없다)
    const mods = import.meta.glob('../assets/vr/*.png', {
      eager: true,
      query: '?url',
      import: 'default',
    }) as Record<string, string>;
    const out: Record<string, string> = {};
    for (const [k, v] of Object.entries(mods ?? {})) {
      const name = k.slice(k.lastIndexOf('/') + 1);
      out[`vr/${name}`] = v;
    }
    return out;
  } catch {
    return {};
  }
})();

/** VRPoint → 화면이 쓸 수 있는 형태. 자산 폴더를 아는 유일한 출구다. */
export function resolveVRPoint(p: VRPoint): ResolvedVRPoint {
  return { ...p, image: VR_ASSETS[p.asset] ?? null };
}

